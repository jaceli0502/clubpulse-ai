const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:960}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const open=async route=>{await page.goto('http://127.0.0.1:4173/?check='+encodeURIComponent(route)+'#'+route);await page.waitForFunction(()=>document.querySelector('#page')?.textContent.length>20)};
 await open('data');await page.locator('#entry-first-date').fill('2026-09-01');await page.locator('#entry-first-attendance').fill('17');
 await page.getByRole('button',{name:'Add Meeting',exact:true}).click();
 await page.waitForFunction(()=>JSON.parse(localStorage.getItem('clubpulse.user-meetings.v1')).records.length===1);
 await page.reload();await page.waitForFunction(()=>document.querySelector('#page')?.textContent.includes('1 meeting'));
 console.log('Direct entry and reload persistence passed');
 await open('import');await page.locator('#csv-file').setInputFiles('tests/product-qa.csv');
 await page.locator('#confirm-import').click();
 await page.waitForFunction(()=>JSON.parse(localStorage.getItem('clubpulse.user-meetings.v1')).records.length>=12);
 const stored=await page.evaluate(()=>localStorage.getItem('clubpulse.user-meetings.v1'));
 await open('overview');await page.locator('[data-meeting-point]').first().click();assert.equal(await page.locator('#chart-point-tooltip').isVisible(),true);
 await page.locator('#chart-meeting').selectOption({index:0});assert.ok(await page.locator('#meeting-details').textContent());
 await page.locator('.ask-disclosure > summary').click();await page.locator('#club-question').fill('Is promotion helping?');await page.locator('#ask-form').evaluate(f=>f.requestSubmit());
 await page.waitForFunction(()=>document.querySelector('#ask-answer')?.textContent.includes('Main signals'));
 console.log('CSV upload, insights, tooltip, inspector and Ask ClubPulse passed');
 await open('predict');await page.waitForSelector('#prediction-output');
 await open('sheets');assert.match(await page.getByRole('link',{name:'Make a Copy in Google Sheets →'}).getAttribute('href'),/^https:\/\/docs.google.com\/spreadsheets/);
 await page.goto('http://127.0.0.1:4173/#demo-video?autoplay=false');await page.waitForFunction(()=>document.body.dataset.videoState==='ready');
 const frame=page.frames().find(f=>f.url().includes('videoSession'));
 await frame.goto('http://127.0.0.1:4173/?videoSession=1#data');await frame.waitForSelector('#entry-first-date');
 assert.match(await frame.locator('#page').textContent(),/Add your first meeting/);
 assert.equal(await page.evaluate(()=>localStorage.getItem('clubpulse.user-meetings.v1')),stored);
 await page.getByRole('link',{name:'Exit',exact:true}).click();await page.waitForSelector('.home-hero');
 assert.equal(await page.locator('.video-stage').count(),0);
 assert.deepEqual(errors,[]);console.log('Planner, Sheets, video privacy and exit passed');await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
